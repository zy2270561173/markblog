"""Markdown rendering and text helpers.

Raw HTML in Markdown is intentionally disabled: authored content is rendered as
HTML elements generated by Markdown-it only, which keeps the admin preview and
the public article safe without a separate sanitizer.
"""

from __future__ import annotations

import html
import math
import re
import unicodedata
from typing import Any
from urllib.parse import urlparse

from markdown_it import MarkdownIt
from markdown_it.token import Token


def _make_markdown() -> MarkdownIt:
    md = MarkdownIt(
        "commonmark",
        {
            "html": False,
            "linkify": False,
            "typographer": True,
            "breaks": False,
        },
    )
    md.enable("table")
    md.enable("strikethrough")

    def heading_open(
        tokens: list[Token], idx: int, options: Any, env: Any
    ) -> str:
        token = tokens[idx]
        inline = tokens[idx + 1] if idx + 1 < len(tokens) else None
        raw = inline.content if inline is not None else ""
        text = re.sub(r"[*_`~\[\]()#]", "", raw)
        heading_id = _heading_slug(text)
        used: dict[str, int] = env.setdefault("heading_ids", {})
        count = used.get(heading_id, 0)
        used[heading_id] = count + 1
        if count:
            heading_id = f"{heading_id}-{count + 1}"
        token.attrSet("id", heading_id)
        return md.renderer.renderToken(tokens, idx, options, env)

    def link_open(tokens: list[Token], idx: int, options: Any, env: Any) -> str:
        token = tokens[idx]
        href = token.attrGet("href") or ""
        token.attrJoin("class", "article-link")
        if href.startswith(("http://", "https://", "//")):
            token.attrSet("target", "_blank")
            token.attrSet("rel", "noopener noreferrer")
        return md.renderer.renderToken(tokens, idx, options, env)

    def image(
        tokens: list[Token], idx: int, options: Any, env: Any
    ) -> str:
        token = tokens[idx]
        token.attrSet("loading", "lazy")
        token.attrSet("decoding", "async")
        token.attrSet("referrerpolicy", "no-referrer")
        return md.renderer.renderToken(tokens, idx, options, env)

    md.renderer.rules["heading_open"] = heading_open
    md.renderer.rules["link_open"] = link_open
    md.renderer.rules["image"] = image
    return md


_MD = _make_markdown()


def _heading_slug(text: str) -> str:
    normalized = unicodedata.normalize("NFKC", text).strip().lower()
    normalized = re.sub(r"[^\w\u3400-\u9fff -]+", "", normalized, flags=re.UNICODE)
    normalized = re.sub(r"[\s_-]+", "-", normalized).strip("-")
    return normalized or "section"


_COMPARE_BLOCK = re.compile(
    r"(?ms)^[ \t]*:::compare[ \t]*\n(.*?)\n[ \t]*:::[ \t]*$"
)


def _safe_image_url(value: str) -> str:
    value = value.strip()
    if value.startswith("/media/") and ".." not in value:
        return value
    parsed = urlparse(value)
    if parsed.scheme in {"http", "https"} and parsed.hostname:
        return value
    return ""


def _compare_html(block: str) -> str:
    values: dict[str, str] = {}
    for line in block.splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        values[key.strip().lower()] = value.strip()
    before = _safe_image_url(values.get("before", ""))
    after = _safe_image_url(values.get("after", ""))
    if not before or not after:
        return ""
    label = html.escape(values.get("label", "维修前后对比"))
    before_label = html.escape(values.get("before_label", "之前"))
    after_label = html.escape(values.get("after_label", "之后"))
    caption = html.escape(values.get("caption", ""))
    return (
        '<figure class="image-compare" data-image-compare>'
        '<div class="image-compare__frame">'
        f'<img class="image-compare__after" src="{html.escape(after, quote=True)}" '
        f'alt="{html.escape(after_label)}" loading="lazy">'
        '<span class="image-compare__before">'
        f'<img src="{html.escape(before, quote=True)}" '
        f'alt="{html.escape(before_label)}" loading="lazy">'
        "</span>"
        f'<span class="image-compare__tag is-before">{before_label}</span>'
        f'<span class="image-compare__tag is-after">{after_label}</span>'
        '<input class="image-compare__range" type="range" min="0" max="100" value="50" '
        f'aria-label="{label}">'
        "</div>"
        f"<figcaption>{label}"
        + (f" · {caption}" if caption else "")
        + "</figcaption></figure>"
    )


def render_markdown(source: str) -> str:
    if not source or not source.strip():
        return ""
    blocks: list[str] = []

    def capture(match: re.Match[str]) -> str:
        rendered = _compare_html(match.group(1))
        if not rendered:
            return match.group(0)
        token = f"COMPAREBLOCKTOKEN{len(blocks)}END"
        blocks.append(rendered)
        return f"\n\n{token}\n\n"

    prepared = _COMPARE_BLOCK.sub(capture, source)
    output = _MD.render(prepared, {})
    for index, rendered in enumerate(blocks):
        token = f"COMPAREBLOCKTOKEN{index}END"
        output = output.replace(f"<p>{token}</p>", rendered)
    return output


def plain_text(source: str) -> str:
    """Turn Markdown into a short, readable line for excerpts and metadata."""

    if not source:
        return ""
    text = re.sub(r"```.*?```", " ", source, flags=re.DOTALL)
    text = re.sub(r"~~~.*?~~~", " ", text, flags=re.DOTALL)
    text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^\s{0,3}#{1,6}\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s{0,3}>\s?", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*[-*+]\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*\d+\.\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"[*_~|]", "", text)
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def make_excerpt(source: str, limit: int = 160) -> str:
    text = plain_text(source)
    if len(text) <= limit:
        return text
    clipped = text[:limit].rstrip("，。；、,. ;:")
    return f"{clipped}……"


def reading_minutes(source: str) -> int:
    text = plain_text(source)
    if not text:
        return 1
    cjk_chars = len(re.findall(r"[\u3400-\u9fff]", text))
    latin_words = len(re.findall(r"[A-Za-z0-9]+(?:['-][A-Za-z0-9]+)*", text))
    minutes = math.ceil(cjk_chars / 300 + latin_words / 220)
    return max(1, minutes)
