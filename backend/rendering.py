"""Markdown rendering and text helpers.

Raw HTML in Markdown is intentionally disabled: authored content is rendered as
HTML elements generated by Markdown-it only, which keeps the admin preview and
the public article safe without a separate sanitizer.
"""

from __future__ import annotations

import html
import math
import re
import unicodedata
from typing import Any

from markdown_it import MarkdownIt
from markdown_it.token import Token


def _make_markdown() -> MarkdownIt:
    md = MarkdownIt(
        "commonmark",
        {
            "html": False,
            "linkify": False,
            "typographer": True,
            "breaks": False,
        },
    )
    md.enable("table")
    md.enable("strikethrough")

    def heading_open(
        tokens: list[Token], idx: int, options: Any, env: Any
    ) -> str:
        token = tokens[idx]
        inline = tokens[idx + 1] if idx + 1 < len(tokens) else None
        raw = inline.content if inline is not None else ""
        text = re.sub(r"[*_`~\[\]()#]", "", raw)
        heading_id = _heading_slug(text)
        used: dict[str, int] = env.setdefault("heading_ids", {})
        count = used.get(heading_id, 0)
        used[heading_id] = count + 1
        if count:
            heading_id = f"{heading_id}-{count + 1}"
        token.attrSet("id", heading_id)
        return md.renderer.renderToken(tokens, idx, options, env)

    def link_open(tokens: list[Token], idx: int, options: Any, env: Any) -> str:
        token = tokens[idx]
        href = token.attrGet("href") or ""
        token.attrJoin("class", "article-link")
        if href.startswith(("http://", "https://", "//")):
            token.attrSet("target", "_blank")
            token.attrSet("rel", "noopener noreferrer")
        return md.renderer.renderToken(tokens, idx, options, env)

    def image(
        tokens: list[Token], idx: int, options: Any, env: Any
    ) -> str:
        token = tokens[idx]
        token.attrSet("loading", "lazy")
        token.attrSet("decoding", "async")
        token.attrSet("referrerpolicy", "no-referrer")
        return md.renderer.renderToken(tokens, idx, options, env)

    md.renderer.rules["heading_open"] = heading_open
    md.renderer.rules["link_open"] = link_open
    md.renderer.rules["image"] = image
    return md


_MD = _make_markdown()


def _heading_slug(text: str) -> str:
    normalized = unicodedata.normalize("NFKC", text).strip().lower()
    normalized = re.sub(r"[^\w\u3400-\u9fff -]+", "", normalized, flags=re.UNICODE)
    normalized = re.sub(r"[\s_-]+", "-", normalized).strip("-")
    return normalized or "section"


def render_markdown(source: str) -> str:
    if not source or not source.strip():
        return ""
    return _MD.render(source, {})


def plain_text(source: str) -> str:
    """Turn Markdown into a short, readable line for excerpts and metadata."""

    if not source:
        return ""
    text = re.sub(r"```.*?```", " ", source, flags=re.DOTALL)
    text = re.sub(r"~~~.*?~~~", " ", text, flags=re.DOTALL)
    text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^\s{0,3}#{1,6}\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s{0,3}>\s?", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*[-*+]\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\s*\d+\.\s+", "", text, flags=re.MULTILINE)
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"[*_~|]", "", text)
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def make_excerpt(source: str, limit: int = 160) -> str:
    text = plain_text(source)
    if len(text) <= limit:
        return text
    clipped = text[:limit].rstrip("，。；、,. ;:")
    return f"{clipped}……"


def reading_minutes(source: str) -> int:
    text = plain_text(source)
    if not text:
        return 1
    cjk_chars = len(re.findall(r"[\u3400-\u9fff]", text))
    latin_words = len(re.findall(r"[A-Za-z0-9]+(?:['-][A-Za-z0-9]+)*", text))
    minutes = math.ceil(cjk_chars / 300 + latin_words / 220)
    return max(1, minutes)
